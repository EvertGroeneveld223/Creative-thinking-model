"""Writes PROMPT_PROGRESS.md: the project's state as one prompt for an LLM that cannot see this repository.
    python make_prompt.py      builds it from the claims already in CLAIMS.md (python claims.py also calls this after rewriting CLAIMS.md)
The text is PROMPT_TEMPLATE.md with each <<MARKER>> replaced by a section of HANDOFF.md, the claim lines of CLAIMS.md, PROOFS.md, or values
computed here by the project's own sequence code. Only the template is written by hand, and it types no result numbers."""
import os, re, sys, textwrap
ROOT = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
for d in ("s6_patches", "s8_proofs"):
    sys.path.insert(0, os.path.join(ROOT, d))
import sym2, general as G
FENCE = "`" * 3
def read(*a): return open(os.path.join(ROOT, *a)).read()
def wrap(text, width=100):
    """Wraps long lines, keeping bullet indents, and drops the markdown bold markers, which mean nothing inside a fence."""
    out = []
    for line in text.replace("**", "").splitlines():
        ind = " " * len(re.match(r"\s*(?:[-*] |\d+\. )?", line).group(0))
        out.append(textwrap.fill(line, width, subsequent_indent=ind, break_long_words=False, break_on_hyphens=False) if line.strip() else "")
    return "\n".join(out)
def handoff(n):
    parts = re.split(r"^## (\d+)\. .*$", read("HANDOFF.md"), flags=re.M)
    return dict(zip(parts[1::2], parts[2::2]))[n].strip()
def proofs(): return read("s8_proofs", "PROOFS.md").split("\n", 1)[1].strip()   # without the title line
def terms(s, n=15):
    co, init = sym2.SEQ[s]; out = list(init)
    while len(out) < n: out.append(sum(c*x for c, x in zip(co, reversed(out[-len(co):]))))
    return out[:n]
NAMES = {"F": "Fibonacci", "L": "Lucas", "P": "Pell", "Q": "Pell-Lucas", "T": "tribonacci"}
def sequences():
    out = []
    for s in "FLPQT":
        co, init = sym2.SEQ[s]
        rec = " + ".join(("" if c == 1 else f"{c}*") + f"{s}(n-{i+1})" for i, c in enumerate(co))
        start = ", ".join(f"{s}({i}) = {x}" for i, x in enumerate(init))
        out.append(f"  {s} ({NAMES[s]}): {s}(n) = {rec}, {start}. n = 0..14: " + " ".join(map(str, terms(s))))
    return "\n".join(out)
def checks(mods=range(2, 31), cyc=range(2, 17)):
    out = [f"  Cycle of each sequence mod m, m = {cyc[0]}..{cyc[-1]}:"]
    for s in "FLPQT": out.append(f"    {s}: " + " ".join(str(sym2.cycle(s, m)) for m in cyc))
    out.append(f"  Exact period of f(g(n)) mod m, m = {mods[0]}..{mods[-1]}, then every m in that range where the R_COMP bound is larger (bound vs exact):")
    for f in "FL":
        for g in "FL":
            ex = {m: G.true_period(f, g, m) for m in mods}; big = [f"m={m}: {G.bound(f, g, m)} vs {e}" for m, e in ex.items() if G.bound(f, g, m) != e]
            out.append(f"    {f}({g}(n)): " + " ".join(map(str, ex.values())))
            out.append("      R_COMP larger at " + ("; ".join(big) if big else "no m in this range"))
    out.append("  Powers of 5 (the case of Theorem 1), exact period:")
    for f, g, ks in (("L", "L", (2, 3, 4)), ("L", "F", (1, 2, 3, 4))):
        out.append(f"    {f}({g}(n)) mod 5^k, k = {ks[0]}..{ks[-1]}: " + " ".join(str(G.true_period(f, g, 5**k)) for k in ks))
    return "\n".join(out)
def claim_lines():
    text = read("CLAIMS.md"); date = re.search(r"Checked (\d{4}-\d\d-\d\d)", text).group(1)
    return [x for x in text.splitlines() if x.startswith("- **C")], date
def build(claims, date):
    prompt = read("PROMPT_TEMPLATE.md").split("\n-8<-\n", 1)[1].strip()
    fill = {"DATE": lambda a: date, "HANDOFF": lambda a: wrap(handoff(a)), "PROOFS": lambda a: wrap(proofs()), "SEQUENCES": lambda a: sequences(),
            "CHECKS": lambda a: checks(), "CLAIMS": lambda a: wrap("\n".join(claims))}
    prompt = re.sub(r"<<([A-Z]+)(?: (\d+))?>>", lambda m: fill[m.group(1)](m.group(2)), prompt)
    if "<<" in prompt or FENCE in prompt: raise ValueError("a marker was left unfilled, or a filled section contains a code fence")
    head = (f"# Progress prompt for LLMs\n\nGenerated by `python make_prompt.py` from PROMPT_TEMPLATE.md, HANDOFF.md, CLAIMS.md (checked {date}) and "
            "s8_proofs/PROOFS.md. Do not edit it by hand. Paste everything inside the fence into an LLM, ideally one that can run code and open "
            "web pages. For the method alone, without this project's state, use PROMPT_FOR_LLMS.md.\n\n")
    return head + FENCE + "\n" + prompt + "\n" + FENCE + "\n"
def write(claims=None, date=None):
    if claims is None: claims, date = claim_lines()
    text = build(claims, date); open(os.path.join(ROOT, "PROMPT_PROGRESS.md"), "w").write(text)
    print(f"wrote PROMPT_PROGRESS.md: {len(claims)} claims, {text.count(chr(10))} lines, {len(text)} characters")
if __name__ == "__main__":
    write()
